export type AppLocale = "en" | "sv";
export type CardLanguage = AppLocale;

export const LOCALE_STORAGE_KEY = "flashstudies-locale";

export function detectDefaultLocale(): AppLocale {
  if (typeof window === "undefined") return "sv";
  const stored = localStorage.getItem(LOCALE_STORAGE_KEY);
  if (stored === "en" || stored === "sv") return stored;
  // Migrate from old key if present
  const legacy = localStorage.getItem("flashcardai-locale");
  if (legacy === "en" || legacy === "sv") {
    localStorage.setItem(LOCALE_STORAGE_KEY, legacy);
    return legacy;
  }
  const browser = navigator.language.toLowerCase();
  return browser.startsWith("sv") ? "sv" : "en";
}

